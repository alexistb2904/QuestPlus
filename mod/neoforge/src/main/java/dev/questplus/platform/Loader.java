package dev.questplus.platform;

import com.google.gson.JsonParser;
import dev.questplus.compat.MinecraftTarget;
import java.io.IOException;
import java.io.InputStreamReader;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.FileSystems;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import net.neoforged.fml.ModList;
import net.neoforged.fml.loading.FMLLoader;
import net.neoforged.fml.loading.FMLPaths;
import org.apache.maven.artifact.versioning.DefaultArtifactVersion;

/**
 * NeoForge implementation of the loader services. Same public methods as {@code mod/fabric}'s
 * (checked by {@code verifyPlatformApi}). Never touches Minecraft classes: mixin plugins call it.
 */
public final class Loader {
	/** Generated by Gradle from {@code versions/<mc>/neoforge/gradle.properties}. */
	static final String TARGETS = "/META-INF/questplus-targets.json";
	private static List<Path> roots;

	private Loader() {}

	public static String name() {
		return "neoforge";
	}

	public static String minecraftVersion() {
		return FMLLoader.getCurrent().getVersionInfo().mcVersion();
	}

	public static String apiName() {
		return "NeoForge";
	}

	public static String apiVersion() {
		return FMLLoader.getCurrent().getVersionInfo().neoForgeVersion();
	}

	public static int compareVersions(String a, String b) {
		return new DefaultArtifactVersion(a).compareTo(new DefaultArtifactVersion(b));
	}

	public static Map<String, MinecraftTarget.Spec> targets() {
		try (var stream = Loader.class.getResourceAsStream(TARGETS)) {
			if (stream == null) throw new IllegalStateException("Quest Plus JAR has no " + TARGETS);
			var specs = new LinkedHashMap<String, MinecraftTarget.Spec>();
			for (var entry : JsonParser.parseReader(new InputStreamReader(stream, StandardCharsets.UTF_8)).getAsJsonObject().entrySet()) {
				var spec = entry.getValue().getAsJsonObject();
				var versions = new ArrayList<String>();
				spec.getAsJsonArray("minecraft").forEach(version -> versions.add(version.getAsString()));
				specs.put(entry.getKey(), new MinecraftTarget.Spec(List.copyOf(versions), spec.get("neoforge").getAsString()));
			}
			return specs;
		} catch (IOException e) {
			throw new UncheckedIOException(e);
		}
	}

	/**
	 * Instantiates the target's adapter class: NeoForge has no entrypoint registry like Fabric's.
	 * Roles: "" CommonAdapterImpl, "/client" ClientAdapterImpl, "/neoforge-client" NeoForgeClientAdapterImpl.
	 */
	public static <T> T adapter(String target, String role, Class<T> type) {
		var name = "dev.questplus.compat." + target + "." + switch (role) {
			case "" -> "CommonAdapterImpl";
			case "/client" -> "ClientAdapterImpl";
			case "/neoforge-client" -> "NeoForgeClientAdapterImpl";
			default -> throw new IllegalArgumentException("Unknown adapter role " + role);
		};
		try {
			return Class.forName(name, true, Loader.class.getClassLoader()).asSubclass(type).getDeclaredConstructor().newInstance();
		} catch (ReflectiveOperationException | ClassCastException e) {
			throw new IllegalStateException("Quest Plus adapter " + name + " is missing or invalid", e);
		}
	}

	public static boolean isModLoaded(String id) {
		var mods = ModList.get();
		if (mods != null) return mods.isLoaded(id);
		// Mixin plugins and early class loading run before ModList exists. Unit tests run without FML.
		var loader = FMLLoader.getCurrentOrNull();
		return loader != null && loader.getLoadingModList().getModFileById(id) != null;
	}

	public static String modVersion() {
		return ModList.get().getModContainerById("questplus").map(c -> c.getModInfo().getVersion().toString()).orElse(null);
	}

	public static Path configDir() {
		return FMLPaths.CONFIGDIR.get();
	}

	public static synchronized List<Path> modRoots() {
		if (roots == null) {
			var found = new ArrayList<Path>();
			for (var file : ModList.get().getModFiles())
				for (var root : file.getFile().getContents().getContentRoots()) {
					try {
						// Jar files are opened once as zip file systems for the lifetime of the game.
						found.add(Files.isRegularFile(root) ? FileSystems.newFileSystem(root).getRootDirectories().iterator().next() : root);
					} catch (IOException | RuntimeException e) {
						// A mod archive Java cannot open contributes no Studio assets.
					}
				}
			roots = List.copyOf(found);
		}
		return roots;
	}
}
